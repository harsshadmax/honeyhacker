"""Turn one observed session into reusable detection content: a Sigma rule and an ATT&CK Navigator layer.

Safety: Sigma is built as a Python dict and serialised with yaml.safe_dump, so hostile text in a command or URL
(quotes, newlines, '---', YAML tags) is escaped by the serialiser and cannot change the document structure.
Output is text for a human to review. Nothing here is applied anywhere.
"""
import re
import uuid
from datetime import datetime, timezone

import yaml

_LEVEL = {"LOW": "low", "MEDIUM": "medium", "HIGH": "high", "CRITICAL": "critical"}
_NS = uuid.UUID("6f1c0c5e-5a4b-4c0e-9a55-4f0d1c7a5e11")
_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")


def clean(s, limit=160) -> str:
    """Printable BMP-only text, capped. Keeps the serialiser away from edge cases (control chars, surrogates)."""
    s = _CTRL.sub("", str(s))
    s = "".join(ch if ord(ch) < 0x10000 else "?" for ch in s)
    return s[:limit]


def _uniq(seq, limit):
    out, seen = [], set()
    for x in seq:
        x = clean(x)
        if x and x not in seen:
            seen.add(x)
            out.append(x)
        if len(out) >= limit:
            break
    return out


def _tag(tid: str) -> str:
    return "attack." + tid.lower()


def to_sigma(session: dict, events: list[dict], attack: dict, behaviour: dict | None = None) -> str:
    """Return a Sigma rule (YAML text) describing what this session actually did. Empty selections are never invented."""
    kinds = {e["kind"] for e in events}
    boring = ("/", "/login", "/favicon.ico")
    # sensitive probes first so they can never be crowded out by a long wordlist scan
    ordered = ([e for e in events if e["kind"] == "sensitive_probe"] +
               [e for e in events if e["kind"] == "request"])
    paths = _uniq((e["detail"].get("path") for e in ordered
                   if e["detail"].get("path") and e["detail"].get("path") not in boring), 12)
    cmds = _uniq((e["detail"].get("cmd", "").split()[0] for e in events
                  if e["kind"] == "suspicious_command" and e["detail"].get("cmd", "").strip()), 8)
    cmd_lines = _uniq((e["detail"].get("cmd") for e in events if e["kind"] == "suspicious_command"), 8)
    tools = (behaviour or {}).get("features", {}).get("tool_user_agents", [])
    users = _uniq((e["detail"].get("username") for e in events if e["kind"] == "login_attempt"), 8)

    detection: dict = {}
    conds = []
    if paths:
        detection["web_paths"] = {"cs-uri-stem|contains": paths}
        conds.append("web_paths")
    if tools:
        detection["tool_agent"] = {"c-useragent|contains": [clean(t) for t in tools]}
        conds.append("tool_agent")
    if cmd_lines:
        detection["shell_commands"] = {"CommandLine|contains": cmd_lines}
        conds.append("shell_commands")
    if "bruteforce_detected" in kinds and users:
        detection["guessed_accounts"] = {"TargetUserName": users}
        conds.append("guessed_accounts")
    if not conds:
        detection["observed_activity"] = {"c-uri|contains": ["/"]}
        conds.append("observed_activity")
    detection["condition"] = " or ".join(conds)

    category = "webserver" if session["service"] == "web" else "process_creation"
    logsource = ({"category": "webserver"} if category == "webserver"
                 else {"category": "process_creation", "product": "linux"})
    techs = []
    for k in kinds:
        a = attack.get(k)
        if a and a[0] not in techs:
            techs.append(a[0])

    rule = {
        "title": clean(f"Hacker Trap observed behaviour ({session['service']}, {_LEVEL.get(session['risk_level'], 'low')})", 100),
        "id": str(uuid.uuid5(_NS, session["id"])),
        "status": "experimental",
        "description": clean(
            "GENERATED from one decoy session. Review before use: patterns come from a single observed attacker "
            "and may be too narrow or too broad.", 300),
        "references": ["https://attack.mitre.org/"],
        "author": "Hacker Trap (auto-generated)",
        "date": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "tags": [_tag(t) for t in techs],
        "logsource": logsource,
        "detection": detection,
        "falsepositives": ["Legitimate vulnerability scanners", "Authorised penetration tests", "Admin scripts"],
        "level": _LEVEL.get(session["risk_level"], "low"),
    }
    header = ("# Generated by Hacker Trap from one observed session. Review and tune before deploying.\n"
              "# Source session: " + clean(session["id"], 60) + "\n")
    return header + yaml.safe_dump(rule, sort_keys=False, allow_unicode=False, width=100)


def to_navigator(session: dict, events: list[dict], attack: dict) -> dict:
    """ATT&CK Navigator layer listing only the techniques this session actually exhibited."""
    seen: dict[str, dict] = {}
    for e in events:
        a = attack.get(e["kind"])
        if not a:
            continue
        t = seen.setdefault(a[0], {"techniqueID": a[0], "score": 0, "comment": clean(a[1], 120), "enabled": True})
        t["score"] += 1
    return {
        "name": clean(f"Hacker Trap session {session['id']}", 80),
        "versions": {"attack": "15", "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Techniques observed in one decoy session. Mapping is indicative, not forensic attribution.",
        "gradient": {"colors": ["#ffe9a8", "#ff4256"], "minValue": 0, "maxValue": max([t["score"] for t in seen.values()] or [1])},
        "techniques": sorted(seen.values(), key=lambda t: t["techniqueID"]),
    }
